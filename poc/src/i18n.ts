export type Key = keyof typeof en;
const dicts: Record<Lang, Dict> = { en, ar };

export function makeT(lang: Lang) {
  const nf = new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', { maximumFractionDigits: 1 });
  const money = new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', {
    style: 'currency', currency: 'EGP', maximumFractionDigits: 0,
  });
  const num = (v: number) => nf.format(v);
  const t = (key: string, vars: Record<string, number> = {}) =>
    ((dicts[lang] as Record<string, string>)[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? num(vars[k]) : `{${k}}`));
  return { t, num, money: (v: number) => money.format(v) };
}

export type T = ReturnType<typeof makeT>;
